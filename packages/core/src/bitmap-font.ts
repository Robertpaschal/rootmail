function assertFontShape(): void {
  for (const [ch, rows] of Object.entries(ROWS)) {
    if (rows.length !== GLYPH_H) {
      throw new Error(`bitmap-font: glyph "${ch}" has ${rows.length} rows, expected ${GLYPH_H}`);
    }
    for (const [i, row] of rows.entries()) {
      if (row.length !== GLYPH_W) {
        throw new Error(`bitmap-font: glyph "${ch}" row ${i} is ${row.length} wide, expected ${GLYPH_W}`);
      }
    }
  }
}
assertFontShape();

/** Rows for a character, or null when unmapped (callers render a blank). */
export function glyph(ch: string): string[] | null {
  return ROWS[ch.toUpperCase()] ?? null;
}

/** Width in pixels of `text` at `scale`, with `tracking` blank columns between glyphs. */
export function textWidth(text: string, scale: number, tracking = 1): number {
  if (text.length === 0) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}
